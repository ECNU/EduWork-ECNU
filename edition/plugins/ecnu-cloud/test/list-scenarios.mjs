import assert from 'node:assert/strict'

export async function listScenarios(page, snap, checks) {
  await page.reload()
  await page.evaluate(() => window.fixture.seedLists())
  const sidebar = page.getByRole('navigation', { name: 'ChatECNU 会话与项目' }), main = page.locator('main')
  const titles = root => root.locator('.ecnu-conversation-row > .ecnu-row').evaluateAll(rows => rows.map(row => row.getAttribute('aria-label')))
  await sidebar.getByRole('button', { name: '已改名的本地续聊', exact: true }).waitFor()
  assert.equal(await sidebar.getByText('最近 3 条', { exact: true }).count(), 1)
  assert.equal(await sidebar.getByText('预览 3 项', { exact: true }).count(), 1)
  for (const label of ['查看全部会话', '查看全部项目']) assert.equal(await sidebar.getByRole('button', { name: label, exact: true }).textContent(), label)
  await sidebar.getByRole('button', { name: '查看全部会话', exact: true }).click()
  await main.getByRole('heading', { name: '会话', exact: true }).waitFor()
  assert.equal(await main.getByRole('tablist').count(), 0)
  assert.deepEqual(await titles(main), ['已改名的本地续聊', '默认工作区本地任务', '其他工作区的普通续聊', '未接续的云端会话'])
  assert.deepEqual(await sidebar.locator('.ecnu-nav-section-body').first().locator('.ecnu-nav-row').evaluateAll(rows => rows.map(row => row.textContent)), ['已改名的本地续聊', '默认工作区本地任务', '其他工作区的普通续聊'])
  await main.getByRole('button', { name: '未接续的云端会话', exact: true }).hover()
  await page.getByRole('tooltip').filter({ hasText: 'ChatECNU 云端会话，点击预览' }).waitFor()
  await snap('unified-conversations')
  await page.mouse.move(900, 60)
  await page.keyboard.press('Tab')
  await main.getByRole('button', { name: '默认工作区本地任务', exact: true }).focus()
  await page.getByRole('tooltip').filter({ hasText: '本地会话，保存在「默认工作区」' }).waitFor()
  const writes = await page.evaluate(() => window.fixture.calls.filter(c => ['cloudImport', 'cloudWorkspaceConnect', 'cloudWorkspaceDisconnect'].includes(c.method)).length)
  await main.getByRole('button', { name: '默认工作区本地任务', exact: true }).press('Enter')
  assert.equal(await page.evaluate(() => window.fixture.opened.at(-1)), 'ordinary-local')
  checks.push('full ordinary list and sidebar share order/icons; default locals and out-of-workspace continuations merge without unrelated, archived or blank sessions; keyboard opens local directly')

  await main.getByRole('button', { name: '查看 云端示例一 的云端原会话', exact: true }).click()
  await main.getByRole('heading', { name: '云端示例一', exact: true }).waitFor()
  await main.getByRole('heading', { name: '下一步' }).waitFor()
  assert.equal(await page.evaluate(() => window.fixture.opened.at(-1)), 'ordinary-local')
  await sidebar.getByRole('button', { name: '查看全部会话', exact: true }).click()
  const destinationReads = await page.evaluate(() => window.fixture.calls.filter(c => c.method === 'cloudDestination').length)
  await main.getByRole('button', { name: '已改名的本地续聊', exact: true }).click()
  assert.equal(await page.evaluate(() => window.fixture.opened.at(-1)), 'ordinary-continued')
  assert.equal(await page.evaluate(() => window.fixture.calls.filter(c => c.method === 'cloudDestination').length), destinationReads)
  checks.push('continued rows use the latest local title, open the existing session, and retain a separate original-cloud preview action')

  await sidebar.getByRole('button', { name: '展开项目 研究项目', exact: true }).click()
  const project = sidebar.locator('.ecnu-nav-project').filter({ has: page.getByRole('button', { name: '展开项目 研究项目', exact: true }) })
  await project.getByRole('button', { name: '项目本地任务', exact: true }).waitFor()
  await project.getByRole('button', { name: '查看 研究项目 的全部会话与资料', exact: true }).click()
  await main.getByRole('tab', { name: '会话', exact: true }).waitFor()
  assert.deepEqual(await titles(main), ['项目本地任务', '项目已接续会话', '云端示例二'])
  assert.deepEqual(await project.locator('.ecnu-nav-chat .ecnu-nav-row').evaluateAll(rows => rows.map(row => row.textContent)), ['项目本地任务', '项目已接续会话', '云端示例二'])
  assert.equal(await project.getByText('3 条会话', { exact: true }).count(), 1)
  assert.deepEqual(await main.locator('[data-conversation-kind]').evaluateAll(rows => rows.map(row => row.getAttribute('data-conversation-kind'))), ['local', 'continued', 'cloud'])
  await main.getByRole('button', { name: '云端示例二', exact: true }).hover()
  await page.getByRole('tooltip').filter({ hasText: 'ChatECNU 云端会话，点击预览' }).waitFor()
  await snap('unified-project-conversations')
  await main.getByRole('button', { name: '项目本地任务', exact: true }).click()
  assert.equal(await page.evaluate(() => window.fixture.opened.at(-1)), 'project-local')
  checks.push('project page and expanded sidebar use the same cloud/local/continued rows, with no duplicate continuation and no foreign workspace sessions')

  await sidebar.getByRole('button', { name: '查看全部项目', exact: true }).click()
  await main.getByRole('heading', { name: '项目', exact: true }).waitFor()
  assert.equal(await main.getByRole('tablist').count(), 0)
  await main.getByRole('button', { name: /额外项目四/ }).waitFor()
  assert.equal(await main.getByRole('button', { name: '研究项目', exact: true }).getAttribute('data-project-status'), 'linked')
  assert.equal(await main.getByRole('button', { name: '额外项目一', exact: true }).getAttribute('data-project-status'), 'cloud')
  await main.getByRole('button', { name: '研究项目', exact: true }).hover()
  await page.getByRole('tooltip').filter({ hasText: '已关联本地工作区「研究项目」，可按需检索云端资料' }).waitFor()
  await snap('project-status-icons')
  await page.setViewportSize({ width: 760, height: 500 })
  for (const label of ['查看全部会话', '查看全部项目']) {
    const entry = sidebar.getByRole('button', { name: label, exact: true })
    await entry.scrollIntoViewIfNeeded()
    assert.equal(await entry.evaluate(node => node.scrollWidth > node.clientWidth), false)
    assert.equal(await entry.evaluate(node => { const r = node.getBoundingClientRect(), hit = document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2); return !!hit && node.contains(hit) }), true)
  }
  const sectionScrolls = () => sidebar.locator('.ecnu-nav-section-body').evaluateAll(rows => rows.map(e => e.scrollTop))
  assert.deepEqual(await sidebar.locator('.ecnu-nav-section-body').evaluateAll(rows => rows.map(e => e.scrollHeight > e.clientHeight)), [false, false])
  await page.locator('aside').evaluate(e => { e.scrollTop = 0 })
  await sidebar.locator('.ecnu-nav-section-body').first().hover()
  await page.mouse.wheel(0, 75)
  await page.waitForFunction(() => document.querySelector('aside').scrollTop > 0)
  const afterChats = await page.locator('aside').evaluate(e => e.scrollTop)
  await sidebar.locator('.ecnu-nav-project-head').first().hover()
  await page.mouse.wheel(0, -40)
  await page.waitForFunction(previous => document.querySelector('aside').scrollTop < previous, afterChats)
  assert.deepEqual(await sectionScrolls(), [0, 0])
  assert.equal(await main.locator('.ecnu-scroll').evaluate(e => e.scrollTop), 0)
  checks.push('cloud groups have natural height; wheel gestures over chats and projects move one sidebar scrollport while the main page stays still; project status icons and hover descriptions match the sidebar')
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await snap('unified-list-more-visible')
  await page.evaluate(() => document.body.setAttribute('data-ds-dark-theme', ''))
  await sidebar.getByRole('button', { name: '查看全部会话', exact: true }).click()
  await snap('unified-list-dark')
  assert.equal(await page.evaluate(() => window.fixture.calls.filter(c => ['cloudImport', 'cloudWorkspaceConnect', 'cloudWorkspaceDisconnect'].includes(c.method)).length), writes)
  checks.push('separate all-conversation/all-project routes have no duplicate tabs; both header actions remain reachable in a short viewport; browsing/navigation create no local or remote records')
}
