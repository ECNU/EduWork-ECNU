import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { join, resolve } from 'node:path'
import { writeFile } from 'node:fs/promises'
const require = createRequire(join(resolve(process.env.EDUWORK_TEST_RUNTIME), 'package.json'))
const { chromium } = require('playwright')
const out = fileURLToPath(new URL('../dist/music-studio/', import.meta.url))
const browser = await chromium.launch({ headless: true, ...(process.env.MUSIC_TEST_BROWSER_CHANNEL ? { channel: process.env.MUSIC_TEST_BROWSER_CHANNEL } : {}) })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' })
page.setDefaultTimeout(15000)
const errors = [], network = []
page.on('pageerror', e => errors.push(e.message))
page.on('request', req => { if (/^https?:/.test(req.url())) network.push(req.url()) })
try {
  await page.goto(pathToFileURL(join(out, 'index.html')).href)
  await page.getByRole('button', { name: '查看可下载产物', exact: true }).click()
  await page.getByRole('button', { name: 'audio.wav ↓', exact: true }).click()
  await page.locator('audio').waitFor()
  await page.locator('audio').evaluate(async audio => { await audio.play(); audio.pause() })
  assert.equal(await page.locator('audio').evaluate(audio => audio.duration > 0), true)
  await page.getByRole('button', { name: 'score.abc ↓', exact: true }).click()
  await page.locator('.ms-detail .ms-score svg').waitFor()
  await page.screenshot({ path: join(out, 'studio-wide.png'), fullPage: true })
  console.log('Audio + ABC preview passed')
  await page.getByRole('button', { name: '用这份谱创作', exact: true }).click()
  assert.match(await page.getByLabel('ABC 乐谱', { exact: true }).inputValue(), /K:C/)
  assert.equal(await page.getByLabel('歌词', { exact: true }).inputValue() !== '', true)
  await page.getByText('生成设置 · 随机种子', { exact: true }).click()
  assert.equal(await page.getByLabel('随机种子 Seed', { exact: true }).inputValue(), '')
  await page.getByLabel('候选数量', { exact: true }).selectOption('2')
  await page.getByRole('button', { name: '生成音乐', exact: true }).click()
  console.log('Two-candidate request submitted')
  await page.getByRole('button', { name: '本次已提交 · 可新建版本', exact: true }).waitFor()
  await page.getByRole('button', { name: '候选 1 · 已完成', exact: true }).waitFor({ timeout: 15000 })
  await page.getByRole('button', { name: '候选 2 · 已完成', exact: true }).click()
  await page.getByRole('button', { name: '查看可下载产物', exact: true }).click()
  await page.getByRole('button', { name: 'score.abc ↓', exact: true }).click()
  await page.locator('.ms-detail .ms-score svg').waitFor()
  await page.getByRole('button', { name: '侧栏宽度', exact: true }).click()
  await page.getByRole('button', { name: '深色', exact: true }).click()
  await page.getByRole('button', { name: '作品详情', exact: true }).click()
  await page.screenshot({ path: join(out, 'studio-sidebar-dark.png'), fullPage: true })
  await page.setViewportSize({ width: 375, height: 812 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await page.getByRole('button', { name: '创作', exact: true }).click()
  await page.getByRole('button', { name: '新建', exact: true }).click()
  await page.getByRole('button', { name: '音频转谱', exact: true }).click()
  assert.equal(await page.getByLabel('歌词', { exact: true }).count(), 0)
  await page.getByLabel('参考音频', { exact: true }).fill('audio/demo.wav')
  await page.getByRole('button', { name: '开始转谱', exact: true }).click()
  await page.getByRole('button', { name: '取消任务', exact: true }).click()
  await page.locator('.ms-detail .ms-status', { hasText: '已取消' }).waitFor()
  await page.getByRole('button', { name: '作品库', exact: true }).click()
  await page.getByLabel('搜索作品').fill('不存在的标题')
  await page.getByText('没有匹配的作品', { exact: false }).waitFor()
  await page.getByLabel('搜索作品').fill('')
  await page.getByRole('button', { name: /晨光与远方 · 交响合唱 创作歌曲/ }).first().click()
  await page.getByRole('button', { name: '查看可下载产物', exact: true }).click()
  await page.getByRole('button', { name: 'score.abc ↓', exact: true }).click()
  await page.locator('.ms-detail .ms-score svg').waitFor()
  await page.screenshot({ path: join(out, 'studio-375.png'), fullPage: true })
  assert.deepEqual(errors, []); assert.deepEqual(network, [])
  const report = { checks: ['file:// offline preview; zero HTTP requests', 'real ABC engraving', 'audio decodes and plays', 'score reuse and lyric preservation', 'random seed omission', 'two candidate flow', 'native-width layout and dark theme', '375 px no horizontal overflow', 'transcription form and cancellation', 'library search'], errors, network }
  await writeFile(join(out, 'browser-checks.json'), JSON.stringify(report, null, 2))
  console.log(JSON.stringify(report))
} catch (error) {
  await page.screenshot({ path: join(out, 'studio-failure.png'), fullPage: true })
  console.error(JSON.stringify({ errors, text: (await page.locator('body').innerText()).slice(-3500) }))
  throw error
} finally { await browser.close() }
