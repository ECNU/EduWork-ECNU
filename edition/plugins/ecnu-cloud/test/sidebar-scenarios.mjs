import assert from 'node:assert/strict'
export async function scenarios(page, snap, checks) {
  const sidebar = page.getByRole('navigation', { name: 'ChatECNU 会话与项目' }), main = page.locator('main')
  const disclosure = sidebar.getByRole('button', { name: 'ChatECNU', exact: true })
  await disclosure.waitFor()
  assert.equal(await disclosure.getAttribute('aria-expanded'), 'false')
  assert.equal(await sidebar.locator('.ecnu-nav-content').count(), 0)
  assert.ok((await sidebar.boundingBox()).y > (await page.getByTestId('native-project').boundingBox()).y)
  await snap('sidebar-local-first-collapsed')
  await disclosure.click()
  await page.reload()
  await sidebar.getByRole('button', { name: /云端示例一/ }).waitFor()
  assert.equal(await disclosure.getAttribute('aria-expanded'), 'true')
  await disclosure.hover()
  assert.equal(await disclosure.locator('.ecnu-nav-chevron').evaluate(el => getComputedStyle(el).transform), 'matrix(0, 1, -1, 0, 0, 0)')
  await disclosure.focus(); await page.keyboard.press('Space')
  assert.equal(await disclosure.getAttribute('aria-expanded'), 'false')
  await page.reload(); await disclosure.waitFor()
  assert.equal(await disclosure.getAttribute('aria-expanded'), 'false')
  await disclosure.click()
  await sidebar.getByRole('button', { name: /云端示例一/ }).waitFor()
  checks.push('native workspaces precede a collapsed cloud section; keyboard toggling and expansion preference survive reload')

  await sidebar.getByRole('button', { name: /云端示例一/ }).click()
  await main.getByRole('heading', { name: '云端示例一' }).waitFor()
  await main.getByRole('heading', { name: '下一步' }).waitFor()
  assert.equal(await page.evaluate(() => window.fixture.imports.size + window.fixture.bindings.size + window.fixture.created.length), 0)
  assert.equal(await page.locator('article img, article script').count(), 0)
  assert.equal(await page.evaluate(() => window.unsafe), undefined)
  assert.equal(await page.getByText('〔图片未加载〕', { exact: true }).count(), 2)
  await snap('sidebar-cloud-read')
  checks.push('sidebar opens cloud history directly; browsing has no local mutation; unsafe HTML/images remain inert')
  await sidebar.getByRole('button', { name: '研究项目', exact: true }).click()
  await main.getByRole('tab', { name: '云端资料 1' }).click()
  await main.getByRole('button', { name: /项目说明.docx/ }).click()
  await main.getByRole('heading', { name: '暂时无法读取正文' }).waitFor()
  await main.getByRole('button', { name: '返回项目资料', exact: true }).click()
  await main.getByRole('tab', { name: '会话', exact: true }).click()
  await main.getByRole('button', { name: /云端示例二/ }).click()
  const draft = main.getByRole('textbox', { name: '在 EduWork 继续这段对话' })
  await draft.fill('继续研究这个项目')
  await main.getByRole('button', { name: '在 EduWork 发送' }).click()
  await main.getByRole('group', { name: '首次本地接续设置' }).waitFor()
  await main.getByRole('button', { name: '取消，保留草稿' }).click()
  assert.equal(await draft.inputValue(), '继续研究这个项目')
  assert.equal(await page.evaluate(() => window.fixture.imports.size + window.fixture.bindings.size + window.fixture.created.length), 0)
  await snap('project-preview-draft')
  checks.push('project source preview and first-send setup are lazy; cancelling preserves the draft with zero writes')
  await main.getByRole('button', { name: '在 EduWork 发送' }).click()
  await main.getByRole('button', { name: '选择或新建工作区' }).click()
  await main.getByRole('button', { name: '项目专用目录' }).click()
  await main.getByRole('button', { name: '确认并发送' }).click()
  await page.waitForFunction(() => window.fixture.sent.length === 1)
  assert.deepEqual(await page.evaluate(() => window.fixture.sent[0]), { id: 'local-cloud-2', text: '继续研究这个项目' })
  assert.equal(await page.evaluate(() => window.fixture.imports.get('cloud-2').workspaceID), 'project-workspace')
  await sidebar.getByRole('button', { name: '研究项目', exact: true }).waitFor()
  assert.equal(await page.getByTestId('native-project').count(), 1)
  const badge = page.getByTestId('native-project').getByRole('button', { name: /已关联 ChatECNU 项目/ })
  await badge.hover()
  await page.getByRole('tooltip').filter({ hasText: '已关联 ChatECNU' }).waitFor()
  await page.mouse.move(550, 20)
  assert.equal(await sidebar.locator('.ecnu-nav-origin').count(), 0)

  await sidebar.getByRole('button', { name: '展开项目 研究项目' }).click()
  await sidebar.getByRole('button', { name: '云端示例二', exact: true }).click()
  await page.waitForFunction(() => window.fixture.opened.length === 2)
  assert.equal(await page.evaluate(() => window.fixture.imports.size), 1)
  await snap('sidebar-project-linked')
  checks.push('first project send binds exactly once, imports into its workspace and transfers the draft; the native workspace stays visible with a hover/focus linkage icon; subsequent clicks reopen the same session')
  await sidebar.getByRole('button', { name: '查看 研究项目 的全部会话与资料', exact: true }).click()
  const freshDraft = main.getByRole('textbox', { name: '在项目中新建会话' })
  await freshDraft.fill('在项目内开始第二个任务')
  await main.getByRole('button', { name: '在 EduWork 发送' }).click()
  await page.waitForFunction(() => window.fixture.sent.length === 2)
  assert.deepEqual(await page.evaluate(() => window.fixture.created), ['project-workspace'])
  checks.push('new project task reuses the same workspace without another directory picker')
  await sidebar.getByRole('button', { name: '查看全部项目' }).click()
  await main.locator('summary').filter({ hasText: '已关联工作区' }).click()
  await main.getByRole('button', { name: '解除 研究项目 的工作区关联' }).click()
  await page.getByTestId('native-project').waitFor()
  assert.equal(await page.getByTestId('native-project').getByRole('button', { name: /已关联 ChatECNU 项目/ }).count(), 0)
  assert.equal(await page.evaluate(() => window.fixture.bindings.size), 0)
  assert.equal(await page.evaluate(() => window.fixture.imports.size), 1)
  checks.push('unlink removes the linkage icon while preserving the native workspace entry and imported history')
  await sidebar.getByRole('button', { name: /云端示例一/ }).click()
  await draft.fill('继续这条普通会话')
  const primary = main.getByRole('button', { name: '在 EduWork 发送' })
  const color = await primary.evaluate(el => ({ color: getComputedStyle(el).color, background: getComputedStyle(el).backgroundColor }))
  assert.deepEqual(color, { color: 'rgb(255, 255, 255)', background: 'rgb(163, 35, 62)' })
  await primary.click(); await page.waitForFunction(() => window.fixture.sent.length === 3)
  assert.equal(await page.evaluate(() => window.fixture.imports.get('cloud-1').workspaceID), 'local-workspace')
  await sidebar.getByRole('button', { name: '云端示例一', exact: true }).waitFor()
  assert.equal(await page.getByTestId('native-chat').count(), 1)
  await page.getByTestId('native-chat').getByRole('button', { name: '来自 ChatECNU，查看云端原会话' }).waitFor()
  checks.push('ordinary chat uses the default local workspace; native conversation remains present with a cloud-source icon')
  await sidebar.getByRole('button', { name: /云端示例三/ }).click()
  await draft.fill('测试保留')
  await page.evaluate(() => document.body.setAttribute('data-ds-dark-theme', ''))
  assert.equal(await primary.evaluate(el => getComputedStyle(el).color), 'rgb(255, 255, 255)')
  await snap('sidebar-dark'); await page.evaluate(() => document.body.removeAttribute('data-ds-dark-theme'))
  await page.setViewportSize({ width: 760, height: 760 }); await snap('sidebar-narrow')
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await page.setViewportSize({ width: 1100, height: 800 })
  checks.push('official RC3 controls retain primary contrast in both themes and fit a narrower desktop window')
  await page.evaluate(() => window.fixture.delay('cloudImport'))
  await primary.click()
  await page.waitForFunction(() => window.fixture.calls.some(c => c.method === 'cloudImport' && c.input.conversationID === 'cloud-3'))
  await page.evaluate(() => window.fixture.logout())
  await page.getByRole('alert').filter({ hasText: '请先在左下角登录学校账号' }).waitFor()
  assert.equal(await page.locator('article').count(), 0)
  assert.ok(await page.evaluate(() => window.fixture.aborted.includes('cloudImport')))
  assert.equal(await page.evaluate(() => window.fixture.sent.length), 3)
  assert.equal(await sidebar.getByRole('button', { name: /云端示例一/ }).count(), 0)
  checks.push('logout clears cloud rows and history, aborts pending import and never submits its draft')
  return color
}
